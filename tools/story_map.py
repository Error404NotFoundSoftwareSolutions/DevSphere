# User story: US-41 Every requirement has a test record (Sprint 9, MVP)
# Requirements: NFR-TEST-001
# Implemented here: scan every source file for 'User story:' header lines and write docs/backlog/STORY_MAP.md

"""Regenerate docs/backlog/STORY_MAP.md: which files implement which story."""

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {"node_modules", ".git", ".venv", "out", "release", "dist", "__pycache__"}
STORY = re.compile(r"User story:\s+((?:SP|US|PL)-[A-Z0-9-]+)")


def scan() -> dict[str, list[str]]:
    found = defaultdict(list)
    for p in ROOT.rglob("*"):
        if (
            not p.is_file()
            or SKIP & set(p.parts)
            or p.name == "STORY_MAP.md"
            or p.suffix in {".json", ".png", ".ico"}
        ):
            continue
        try:
            text = p.read_text(encoding="utf-8")[:2000]
        except (UnicodeDecodeError, OSError):
            continue
        for sid in STORY.findall(text):
            found[sid].append(p.relative_to(ROOT).as_posix())
    return found


def main() -> int:
    found = scan()
    lines = [
        "# Story map",
        "",
        "Generated by `python tools/story_map.py`. Do not edit by hand.",
        "",
        "| Story | Files |",
        "|---|---|",
    ]
    for sid in sorted(found):
        lines.append(f"| {sid} | " + "<br>".join(f"`{f}`" for f in sorted(found[sid])) + " |")
    out = ROOT / "docs/backlog/STORY_MAP.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(found)} stories mapped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
